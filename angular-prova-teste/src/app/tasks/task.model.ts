/**
 * Values accepted by the Java API (`@Pattern` in `TaskRequest`).
 * Keep the strings exactly as the backend validates them — including the space in
 * "EM ANDAMENTO" — otherwise `POST /tasks` is rejected with 400.
 */
export type TaskStatus = 'PENDENTE' | 'EM ANDAMENTO' | 'CONCLUIDA';
export type TaskPriority = 'BAIXA' | 'MEDIA' | 'ALTA';

/** Item returned by `GET /tasks` (`TaskResponse` on the Java side). */
export interface Task {
  id: number;
  title: string;
  description: string;
  responsible: string;
  status: TaskStatus;
  priority: TaskPriority;
}

/** Payload accepted by `POST /tasks` — the id is generated by the API. */
export type CreateTaskInput = Omit<Task, 'id'>;

export const TASK_STATUS: Record<TaskStatus, { label: string; badge: string }> = {
  PENDENTE: { label: 'Pendente', badge: 'secondary' },
  'EM ANDAMENTO': { label: 'Em andamento', badge: 'primary' },
  CONCLUIDA: { label: 'Concluída', badge: 'success' },
};

export const TASK_PRIORITY: Record<TaskPriority, { label: string; badge: string }> = {
  ALTA: { label: 'Alta', badge: 'danger' },
  MEDIA: { label: 'Média', badge: 'warning' },
  BAIXA: { label: 'Baixa', badge: 'info' },
};

export const TASK_STATUS_OPTIONS = (Object.keys(TASK_STATUS) as TaskStatus[]).map((value) => ({
  value,
  label: TASK_STATUS[value].label,
}));

export const TASK_PRIORITY_OPTIONS = (Object.keys(TASK_PRIORITY) as TaskPriority[]).map((value) => ({
  value,
  label: TASK_PRIORITY[value].label,
}));
